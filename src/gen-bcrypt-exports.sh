# Generates the export list, jump stubs and .def for the bcrypt.dll stand-in (bcrypt.c) from the
# export table of an installed Wine bcrypt.dll, so the stand-in forwards exactly what that Wine exports.
#
# Usage: gen-bcrypt-exports.sh WINE_BCRYPT_DLL OUTDIR
# Writes OUTDIR/bcrypt-exports.h, OUTDIR/bcrypt-thunks.S, OUTDIR/bcrypt.def.

set -euo pipefail
dll="${1:?usage: $0 WINE_BCRYPT_DLL OUTDIR}"
out="${2:?usage: $0 WINE_BCRYPT_DLL OUTDIR}"
mkdir -p "$out"

# Functions implemented in bcrypt.c rather than forwarded by a jump stub.
own=" BCryptImportKeyPair BCryptDecrypt BCryptDestroyKey "

# objdump -p prints the export name table as lines like "	[  12] BCryptDecrypt".
mapfile -t names < <(x86_64-w64-mingw32-objdump -p "$dll" \
    | awk '/\[Ordinal\/Name Pointer\] Table/ { t = 1; next } t && /^\t\[ *[0-9]+\] / { print $NF } t && /^$/ { exit }')
[[ ${#names[@]} -gt 0 ]] || { echo "no exports found in $dll" >&2; exit 1; }
for n in $own; do
    printf '%s\n' "${names[@]}" | grep -qx "$n" || { echo "$dll doesn't export $n" >&2; exit 1; }
done

{
    echo "/* Generated by gen-bcrypt-exports.sh from $(basename "$dll"); order matches bcrypt-thunks.S. */"
    echo 'static const char *const export_names[] ='
    echo '{'
    printf '    "%s",\n' "${names[@]}"
    echo '};'
    for i in "${!names[@]}"; do
        [[ "$own" == *" ${names[$i]} "* ]] && echo "#define IDX_${names[$i]} $i"
    done
} > "$out/bcrypt-exports.h"

{
    echo '/* Generated by gen-bcrypt-exports.sh: jump stubs forwarding to the real bcrypt.dll.'
    echo ' * real_bcrypt[i] is filled in by bcrypt.c in export_names order. */'
    echo '    .text'
    for i in "${!names[@]}"; do
        [[ "$own" == *" ${names[$i]} "* ]] && continue
        printf '    .globl %s\n%s:\n    jmp *real_bcrypt+%d(%%rip)\n' "${names[$i]}" "${names[$i]}" $((8 * i))
    done
} > "$out/bcrypt-thunks.S"

{
    echo 'LIBRARY bcrypt.dll'
    echo 'EXPORTS'
    printf '    %s\n' "${names[@]}"
} > "$out/bcrypt.def"

echo "${#names[@]} exports"
